import { jsPDF } from 'jspdf';
import { DataCenterConfig, EngineeringCalculation } from '../types/datacenter';
import { calculatePersonaROI } from './engineeringEngine';

export function generateFEEDPdfDeck(config: DataCenterConfig, calc: EngineeringCalculation): jsPDF {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const roi = calculatePersonaROI('neocloud', config, calc);
  const pageWidth = 210;
  const pageHeight = 297;
  const margin = 14;
  const contentWidth = pageWidth - (margin * 2);

  const drawHeader = (pageNum: number, totalPages: number, pageTitle: string) => {
    // Top navy bar
    doc.setFillColor(15, 23, 42);
    doc.rect(margin, 12, contentWidth, 14, 'F');
    
    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text('AZ DATA CENTER DESIGN STUDIO · FEED STUDY', margin + 4, 21);
    
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.text('DOC-REF: AZ-FEED-2026-0928 | CONFIDENTIAL', pageWidth - margin - 4, 21, { align: 'right' });

    // Subheader title bar
    doc.setTextColor(30, 41, 59);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.text(pageTitle, margin, 34);

    doc.setDrawColor(203, 213, 225);
    doc.setLineWidth(0.4);
    doc.line(margin, 37, pageWidth - margin, 37);

    // Footer
    doc.setDrawColor(226, 232, 240);
    doc.line(margin, pageHeight - 12, pageWidth - margin, pageHeight - 12);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(100, 116, 139);
    doc.text('Generated by AZ Engineering Synthesis Engine · Mission-Critical Infrastructure Solutions', margin, pageHeight - 8);
    doc.text(`Page ${pageNum} of ${totalPages}`, pageWidth - margin, pageHeight - 8, { align: 'right' });
  };

  // PAGE 1: EXECUTIVE PROJECT BASELINE & COMPUTATIONAL PROFILE
  drawHeader(1, 4, '1. Executive Project Summary & Facility Baseline');

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(51, 65, 85);
  const summaryP1 = `This Front-End Engineering Design (FEED) study package establishes the technical architecture, physics calculations, and commercial capital expenditure model for a ${calc.facilityTotalLoadMW} MW mission-critical AI supercomputing facility optimized for ${config.gpuType.toUpperCase()} accelerator racks.`;
  doc.text(doc.splitTextToSize(summaryP1, contentWidth), margin, 43);

  // 4 Key Metric Cards
  const cardY = 52;
  const cardW = (contentWidth - 9) / 4;
  const cardH = 19;

  const metrics = [
    { label: 'CRITICAL IT LOAD', val: `${calc.criticalITLoadMW.toFixed(1)} MW`, color: [29, 78, 216] },
    { label: 'TOTAL FACILITY LOAD', val: `${calc.facilityTotalLoadMW} MW`, color: [15, 23, 42] },
    { label: 'DESIGN PUE', val: calc.pue.toFixed(2), color: [16, 185, 129] },
    { label: 'ESTIMATED CAPEX', val: `$${calc.totalCapExM}M`, color: [5, 150, 105] },
  ];

  metrics.forEach((m, idx) => {
    const cx = margin + idx * (cardW + 3);
    doc.setFillColor(248, 250, 252);
    doc.setDrawColor(226, 232, 240);
    doc.rect(cx, cardY, cardW, cardH, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(6.5);
    doc.setTextColor(100, 116, 139);
    doc.text(m.label, cx + cardW / 2, cardY + 6, { align: 'center' });

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(m.color[0], m.color[1], m.color[2]);
    doc.text(m.val, cx + cardW / 2, cardY + 14.5, { align: 'center' });
  });

  // Specifications Table
  let tableY = 78;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.setTextColor(15, 23, 42);
  doc.text('Key Technical Dimensions & Computational Density', margin, tableY);

  tableY += 4;
  const tableData1 = [
    ['Silicon Accelerator Architecture', `${config.gpuType.toUpperCase()} High-Density Compute Clusters`],
    ['Total GPU Scale', `${config.ingressMode === 'top-down' ? config.gpuCount.toLocaleString() : (calc.totalRacks * 72).toLocaleString()} Accelerated Silicon Processors`],
    ['Total Compute Racks & Density', `${calc.totalRacks.toLocaleString()} Racks at ${calc.rackDensityKW} kW/Rack Target Density`],
    ['Facility Footprint (White Space)', `${calc.totalFootprintSqFt.toLocaleString()} sq ft Total (${calc.whiteSpaceSqFt.toLocaleString()} sq ft White Space)`],
    ['Civil Land Allocation', `${config.landAcreage} Acres required for Substation Yard & Campus`],
    ['Floor Slab Loading Capacity', `${calc.structuralSlabLoadPcf} lbs/sq ft Hardened Reinforced Concrete`],
    ['Cooling Heat Dissipation', `${calc.heatDissipationTons.toLocaleString()} Tons Total Heat Rejection Capacity`],
    ['Coolant Flow Circulation', `${calc.totalCoolantFlowGPM.toLocaleString()} GPM Closed-Loop Liquid Flow`],
    ['Water Usage Effectiveness (WUE)', `${calc.wue} L/kWh (Closed-Loop ${config.rejectionPlant.toUpperCase()})`],
    ['Carbon Usage Effectiveness (CUE)', `${calc.cue} kg CO2/kWh Facility Emission Baseline`],
    ['Unit Capital Intensity', `$${calc.capexPerMW}M per Megawatt of Utility Grid Power`],
    ['Annual Utility Power OpEx', `$${calc.annualPowerCostM}M per Annum at Baseload`],
    ['Commercial Operation Date (COD)', `${calc.projectedCODDate} (${calc.criticalPathWeeks} Weeks Total Path)`],
    ['Critical Long-Lead Bottleneck', `${calc.bottleneckComponent}`]
  ];

  doc.setFillColor(241, 245, 249);
  doc.rect(margin, tableY, contentWidth, 6.5, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7.5);
  doc.setTextColor(71, 85, 105);
  doc.text('PARAMETER', margin + 3, tableY + 4.5);
  doc.text('ENGINEERING VALUE & SPECIFICATION', margin + 70, tableY + 4.5);

  tableY += 6.5;
  tableData1.forEach((row, i) => {
    if (i % 2 === 1) {
      doc.setFillColor(248, 250, 252);
      doc.rect(margin, tableY, contentWidth, 6.2, 'F');
    }
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7);
    doc.setTextColor(51, 65, 85);
    doc.text(row[0], margin + 3, tableY + 4.2);

    doc.setFont('helvetica', 'normal');
    doc.setTextColor(15, 23, 42);
    doc.text(row[1], margin + 70, tableY + 4.2);

    doc.setDrawColor(241, 245, 249);
    doc.line(margin, tableY + 6.2, margin + contentWidth, tableY + 6.2);
    tableY += 6.2;
  });

  // PAGE 2: ARCHITECTURAL & ENGINEERING SUBSYSTEMS
  doc.addPage();
  drawHeader(2, 4, '2. Architectural & Engineering Subsystems');

  let subY = 44;
  const subsystems = [
    {
      title: 'High-Voltage Substation Yard',
      spec: `${config.substationType.toUpperCase()} Substation Lineup`,
      desc: `Configured with ${config.dualUtilityFeed ? 'Dual 115kV/230kV Feeds' : 'Single 115kV Feed'}. Footprint spans ${calc.substationYardSqFt.toLocaleString()} sq ft with a 100kA short-circuit withstand rating and GIS breaker lineup.`
    },
    {
      title: 'Main Medium-Voltage Transformation',
      spec: config.transformerType === 'sst' ? 'Solid-State Transformers (SST)' : 'Conventional Oil-Filled MV Transformers (LPT)',
      desc: `Stepping down from 34.5kV to 4.16kV with ${config.redundancy.toUpperCase()} redundancy. ${config.transformerType === 'sst' ? 'SST technology bypasses standard 110-week large power transformer supply bottlenecks.' : 'Conventional oil-filled transformers with oil containment sumps.'}`
    },
    {
      title: 'White Space Power Distribution',
      spec: config.serverPower === '800vdc' ? '800V DC Central Busway Architecture' : '480V AC Conventional Distribution',
      desc: config.serverPower === '800vdc'
        ? '98.4% end-to-end distribution efficiency eliminating intermediate AC/DC conversion losses directly feeding high-power GPU shelves.'
        : '3-phase 480V AC distribution with dedicated PDUs and remote power panels (RPPs).'
    },
    {
      title: 'Liquid Cooling & Thermal Rejection',
      spec: `Direct-to-Chip (D2C) Liquid CDUs + ${config.rejectionPlant.toUpperCase()}`,
      desc: `High-efficiency liquid distribution pumping ${calc.totalCoolantFlowGPM.toLocaleString()} GPM to dissipate ${calc.heatDissipationTons.toLocaleString()} Tons of heat with closed-loop adiabatic rejection.`
    },
    {
      title: 'Behind-the-Meter (BTM) Generation & BESS',
      spec: `${config.btmPower.toUpperCase()} + ${config.bessType.toUpperCase()} Storage`,
      desc: `Fast-track onsite dispatchable power to mitigate grid interconnect queues and provide critical bridge power during grid curtailment events.`
    },
    {
      title: 'Civil, Structural Shell & Foundations',
      spec: config.envelopeType === 'modular_skid' ? 'Pre-Fabricated Modular Container Skids' : 'Hardened Concrete Slab-on-Grade',
      desc: `High-density seismic foundation engineered for ${calc.structuralSlabLoadPcf} lbs/sq ft structural load across ${calc.totalFootprintSqFt.toLocaleString()} sq ft total building footprint.`
    }
  ];

  subsystems.forEach(sub => {
    doc.setFillColor(248, 250, 252);
    doc.setDrawColor(226, 232, 240);
    doc.roundedRect(margin, subY, contentWidth, 23, 1.5, 1.5, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.setTextColor(29, 78, 216);
    doc.text(sub.title, margin + 4, subY + 6);

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(15, 23, 42);
    doc.text(sub.spec, margin + 85, subY + 6);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(71, 85, 105);
    doc.text(doc.splitTextToSize(sub.desc, contentWidth - 8), margin + 4, subY + 12);

    subY += 26;
  });

  // PAGE 3: BILL OF MATERIALS & SCHEDULE
  doc.addPage();
  drawHeader(3, 4, '3. Itemized Bill of Materials (BOM) & Critical Path');

  let bomY = 44;
  const bomRowsData = [
    ['High-Voltage Substation Package & GIS Lineup', '50–64 Wks', `$${calc.substationCapExM.toFixed(1)}M`],
    ['Medium-Voltage Transformation & Switchgear', config.transformerType === 'sst' ? '44 Wks' : '110 Wks', `$${calc.transformersCapExM.toFixed(1)}M`],
    ['Behind-the-Meter Generation (BTM Engine/Turbine)', '20–72 Wks', `$${calc.btmGenCapExM.toFixed(1)}M`],
    ['UPS Battery & Energy Storage System (BESS)', '32–40 Wks', `$${calc.bessCapExM.toFixed(1)}M`],
    ['Liquid Cooling CDUs & Heat Rejection Farm', '36–52 Wks', `$${calc.coolingPlantCapExM.toFixed(1)}M`],
    ['Power Distribution Architecture (Busways/PDUs)', '28–45 Wks', `$${calc.powerDistributionCapExM.toFixed(1)}M`],
    ['Civil, Structural Shell & Foundations', '32–68 Wks', `$${calc.civilStructuralCapExM.toFixed(1)}M`],
    ['EPC Management, Permitting, Level 1-5 Cx', 'Continuous', `$${calc.epcManagementCapExM.toFixed(1)}M`]
  ];

  doc.setFillColor(241, 245, 249);
  doc.rect(margin, bomY, contentWidth, 7, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7.5);
  doc.setTextColor(71, 85, 105);
  doc.text('EQUIPMENT / WORK PACKAGE', margin + 3, bomY + 5);
  doc.text('LEAD TIME', margin + 115, bomY + 5);
  doc.text('ESTIMATED CAPEX ($M)', margin + contentWidth - 3, bomY + 5, { align: 'right' });

  bomY += 7;
  bomRowsData.forEach((row, i) => {
    if (i % 2 === 1) {
      doc.setFillColor(248, 250, 252);
      doc.rect(margin, bomY, contentWidth, 7, 'F');
    }
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(51, 65, 85);
    doc.text(row[0], margin + 3, bomY + 5);

    doc.setFont('helvetica', 'normal');
    doc.setTextColor(71, 85, 105);
    doc.text(row[1], margin + 115, bomY + 5);

    doc.setFont('helvetica', 'bold');
    doc.setTextColor(15, 23, 42);
    doc.text(row[2], margin + contentWidth - 3, bomY + 5, { align: 'right' });

    doc.setDrawColor(241, 245, 249);
    doc.line(margin, bomY + 7, margin + contentWidth, bomY + 7);
    bomY += 7;
  });

  // Total BOM Row
  doc.setFillColor(224, 231, 255);
  doc.rect(margin, bomY, contentWidth, 8, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(30, 58, 138);
  doc.text('TOTAL ESTIMATED CAPEX (TURNKEY FACILITY):', margin + 3, bomY + 5.5);
  doc.text(`$${calc.totalCapExM.toFixed(1)}M`, margin + contentWidth - 3, bomY + 5.5, { align: 'right' });

  // Schedule Callout Box
  bomY += 15;
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(203, 213, 225);
  doc.roundedRect(margin, bomY, contentWidth, 34, 1.5, 1.5, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(15, 23, 42);
  doc.text('Critical Path & Milestone Execution Plan', margin + 4, bomY + 6);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(71, 85, 105);
  doc.text(`• Critical Path Bottleneck: ${calc.bottleneckComponent} (${calc.criticalPathWeeks} Weeks Total Lead Time)`, margin + 4, bomY + 13);
  doc.text(`• Earliest Target Commercial Operation Date (COD): ${calc.projectedCODDate}`, margin + 4, bomY + 20);
  doc.text(`• Schedule Compression Strategy: Early procurement of critical power transformation saves up to 26 weeks.`, margin + 4, bomY + 27);

  // PAGE 4: COMMERCIAL ROI & EXECUTIVE SIGN-OFF
  doc.addPage();
  drawHeader(4, 4, '4. Financial Feasibility & Engineering Sign-Off');

  let roiY = 44;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(15, 23, 42);
  doc.text('Commercial Model: Neocloud AI Service Provider Baseline', margin, roiY);

  roiY += 5;
  const roiMetrics = [
    { label: 'ANNUAL REVENUE', val: roi.primaryStatValue },
    { label: 'PROJECTED IRR', val: roi.secondaryStatValue },
    { label: 'CAPEX PAYBACK', val: roi.tertiaryStatValue },
  ];
  const rCardW = (contentWidth - 6) / 3;
  roiMetrics.forEach((m, idx) => {
    const rx = margin + idx * (rCardW + 3);
    doc.setFillColor(248, 250, 252);
    doc.setDrawColor(226, 232, 240);
    doc.rect(rx, roiY, rCardW, 18, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(6.5);
    doc.setTextColor(100, 116, 139);
    doc.text(m.label, rx + rCardW / 2, roiY + 6, { align: 'center' });

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10.5);
    doc.setTextColor(29, 78, 216);
    doc.text(m.val, rx + rCardW / 2, roiY + 14, { align: 'center' });
  });

  // Formal Sign-off and Authorization Blocks
  let sigY = roiY + 36;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(15, 23, 42);
  doc.text('Engineering Governance & Executive Authorization', margin, sigY);

  sigY += 5;
  doc.setDrawColor(203, 213, 225);
  doc.line(margin, sigY, margin + contentWidth, sigY);

  sigY += 10;
  const boxW = (contentWidth - 10) / 2;

  // Prepared by
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7.5);
  doc.setTextColor(15, 23, 42);
  doc.text('PREPARED & AUTHORIZED BY:', margin, sigY);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);
  doc.setTextColor(71, 85, 105);
  doc.text('AZ Data Center Studio — Senior Solutions Architecture Team', margin, sigY + 5);
  doc.text('Director of Electrical & Mechanical Engineering', margin, sigY + 9);
  doc.setDrawColor(148, 163, 184);
  doc.line(margin, sigY + 28, margin + boxW, sigY + 28);
  doc.setFontSize(6.5);
  doc.setTextColor(148, 163, 184);
  doc.text('Authorized Signature & Engineering Stamp', margin, sigY + 32);

  // Accepted by
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7.5);
  doc.setTextColor(15, 23, 42);
  doc.text('ACCEPTED & RECEIVED BY:', margin + boxW + 10, sigY);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);
  doc.setTextColor(71, 85, 105);
  doc.text('Client Infrastructure & Investment Committee', margin + boxW + 10, sigY + 5);
  doc.text('Chief Technology Officer / Infrastructure Sponsor', margin + boxW + 10, sigY + 9);
  doc.setDrawColor(148, 163, 184);
  doc.line(margin + boxW + 10, sigY + 28, margin + contentWidth, sigY + 28);
  doc.setFontSize(6.5);
  doc.setTextColor(148, 163, 184);
  doc.text('Client Executive Signature & Date', margin + boxW + 10, sigY + 32);

  return doc;
}
